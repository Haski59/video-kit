/**
 * engine/captions/ass.js — deterministic ASS for libass. Pure.
 *
 * assTime / escapeAss / assColour are ported from scripts/edit/pure.js. NEW: per-word emphasis
 * colour, an explicit \pos so the caption sits exactly where the planner's face-aware layout put
 * it (alignment margins cannot express "below the chin"), and a short fade-in only.
 *
 * The output frame is the reference frame (PlayRes = output px), so every size here is a real
 * output pixel and QC can predict the caption box from the same numbers.
 */

export function assTime(sec) {
  const t = Math.max(0, sec);
  const h = Math.floor(t / 3600), m = Math.floor((t % 3600) / 60), s = Math.floor(t % 60);
  const cs = Math.round((t - Math.floor(t)) * 100);
  if (cs === 100) return assTime(Math.floor(t) + 1);
  return `${h}:${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}.${String(cs).padStart(2, "0")}`;
}

/** `{`/`}` open/close override blocks and `\` starts escapes — neutralise all three. */
export function escapeAss(text) {
  return String(text).replace(/\\/g, "").replace(/\{/g, "\\{").replace(/\}/g, "\\}").replace(/\r?\n/g, " ").replace(/\s+/g, " ").trim();
}

/** #RRGGBB or #AARRGGBB → &HAABBGGRR (ASS: BGR, inverted alpha). */
export function assColour(hex) {
  const h = String(hex).replace(/^#/, "").trim();
  const has8 = h.length === 8;
  const a = has8 ? Number.parseInt(h.slice(0, 2), 16) : 255;
  const rgb = has8 ? h.slice(2) : h;
  if (!/^[0-9a-fA-F]{6}$/.test(rgb)) throw new Error(`assColour: not a hex colour: ${hex}`);
  const [r, g, b] = [0, 2, 4].map((i) => Number.parseInt(rgb.slice(i, i + 2), 16));
  return `&H${[255 - a, b, g, r].map((v) => v.toString(16).toUpperCase().padStart(2, "0")).join("")}`;
}

/** Inline colour override form: &HBBGGRR& */
export const assInline = (hex) => `&H${assColour(hex).slice(4)}&`;

/**
 * Approximate rendered box of a cue (output px) — what the planner and QC use for collision maths.
 * Avenir Next Bold averages ~0.56em per character; the estimate is deliberately generous.
 */
export function cueBox(cue, style, centre) {
  const lines = cue.lines.map((idx) => idx.map((k) => cue.words[k].text).join(" "));
  const longest = Math.max(...lines.map((l) => (style.uppercase ? l.toUpperCase() : l).length));
  const w = Math.min(centre.maxWidth ?? Infinity, longest * style.fontSize * (style.charWidthEm ?? 0.6) + style.outline * 2);
  const h = lines.length * style.fontSize * 1.2 + style.outline * 2;
  return { x: centre.x - w / 2, y: centre.y - h / 2, w, h };
}

export function buildAss({ cues, style, width, height, position }) {
  if (!Number.isFinite(width) || !Number.isFinite(height)) throw new Error("buildAss: width/height required");
  if (!position || !Number.isFinite(position.x) || !Number.isFinite(position.y)) throw new Error("buildAss: caption position required");
  const header = [
    "[Script Info]",
    "; Generated by the video kit engine — regenerate from the edit plan, do not hand-edit.",
    "ScriptType: v4.00+",
    `PlayResX: ${Math.round(width)}`,
    `PlayResY: ${Math.round(height)}`,
    "WrapStyle: 2",
    "ScaledBorderAndShadow: yes",
    "YCbCr Matrix: TV.709",
    "",
    "[V4+ Styles]",
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
    ["Style: Cap", style.font, style.fontSize, assColour(style.primaryColour), assColour(style.primaryColour), assColour(style.outlineColour),
      assColour("#80000000"), style.bold ? -1 : 0, 0, 0, 0, 100, 100, 0, 0, 1, style.outline, style.shadow, 5, 0, 0, 0, 1].join(","),
    "",
    "[Events]",
    "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
  ];
  const base = assInline(style.primaryColour), emph = assInline(style.emphasisColour);
  const events = cues.map((c) => {
    const lines = c.lines.map((idx) => idx.map((k) => {
      const w = c.words[k];
      const t = escapeAss(style.uppercase ? w.text.toUpperCase() : w.text);
      return w.emphasis ? `{\\c${emph}}${t}{\\c${base}}` : t;
    }).join(" "));
    const fade = style.fadeInMs ? `\\fad(${Math.round(style.fadeInMs)},0)` : "";
    return `Dialogue: 0,${assTime(c.start)},${assTime(c.end)},Cap,,0,0,0,,{\\an5\\pos(${Math.round(position.x)},${Math.round(position.y)})${fade}}${lines.join("\\N")}`;
  });
  return `${header.concat(events).join("\n")}\n`;
}
